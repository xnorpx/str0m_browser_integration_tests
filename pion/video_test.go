func ddTestPacket(t *testing.T, wire string, sequence uint16, timestamp uint32) *rtp.Packet {
	t.Helper()
	raw, err := hex.DecodeString(wire)
	if err != nil {
		t.Fatal(err)
	}
	packet := &rtp.Packet{Header: rtp.Header{
		Version: 2, PayloadType: 45, SSRC: 42, SequenceNumber: sequence,
		Timestamp: timestamp, Marker: raw[0]&64 != 0,
	}, Payload: []byte{1}}
	if err := packet.SetExtension(13, raw); err != nil {
		t.Fatal(err)
	}
	return packet
}

func TestDDReceiverParsesStr0mWireFixturesAndDependencies(t *testing.T) {
	video := newDDVideoReceiver(13)
	var sequence uint16 = 65530
	for index := range 32 {
		number := uint16((65530 + index) % 65536)
		timestamp := uint32(index * 9000)
		// These are str0m's actual wire encodings, not generated by LiveKit.
		raw := []byte{0xc1, byte(number >> 8), byte(number)}
		packets := [][]byte{raw}
		if index == 0 || index == 16 {
			packets = [][]byte{
				{0x80, byte(number >> 8), byte(number), 0x80, 0, 0x3b, 0x40, 0},
				{0, byte(number >> 8), byte(number), 0, 0},
				{0x40, byte(number >> 8), byte(number), 0, 0},
			}
		}
		for _, wire := range packets {
			packet := ddTestPacket(t, hex.EncodeToString(wire), sequence, timestamp)
			if err := video.receive(packet); err != nil {
				t.Fatalf("frame %d sequence %d: %v", index, sequence, err)
			}
			sequence++
		}
	}
	server := &SessionReport{VideoFrameMode: &FrameVideoReport{
		RustFramesSent: 32, RustToChrome: DdPacketSummary{Packets: 36, Frames: 32, Structures: 2},
	}}
	profile := map[string]any{
		"schema_version": 2, "dd_extension_id": 13,
		"rust_to_chrome": make([]DDVideoPacket, len(video.report.Packets)),
	}
	source := profile["rust_to_chrome"].([]DDVideoPacket)
	for i, packet := range video.report.Packets {
		packet.Descriptor = nil
		source[i] = packet
	}
	filename := filepath.Join(t.TempDir(), "source.json")
	writeSource := func() {
		t.Helper()
		data, err := json.Marshal(profile)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filename, data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	writeSource()
	if err := compareVideoSource(&video.report, filename); err != nil {
		t.Fatal(err)
	}
	if err := validateVideoReport(&video.report, server); err != nil {
		t.Fatal(err)
	}
	if video.inFrame || video.report.Roundtrips != 36 || video.report.FrameNumberWraps != 1 {
		t.Fatalf("incorrect final receiver state: %+v", video.report)
	}
	server.VideoFrameMode.RustToChrome.Packets++
	if err := validateVideoReport(&video.report, server); err == nil {
		t.Fatal("accepted inconsistent str0m packet count")
	}
	source[0].DDHex = "changed"
	writeSource()
	if err := compareVideoSource(&video.report, filename); err == nil {
		t.Fatal("accepted different wire DD bytes")
	}
	if err := compareVideoSource(&video.report, filepath.Join(t.TempDir(), "missing.json")); err == nil {
		t.Fatal("accepted a missing source profile")
	}
}

func TestDDReceiverRejectsMissingStructureMalformedAndMissingDD(t *testing.T) {
	for _, wire := range []string{"80", "80fffa", "40fffa0000", "80fffa80"} {
		t.Run(wire, func(t *testing.T) {
			if err := newDDVideoReceiver(13).receive(ddTestPacket(t, wire, 1, 0)); err == nil {
				t.Fatal("accepted invalid or structure-less descriptor")
			}
		})
	}
	packet := ddTestPacket(t, "c0fffa80003b4000", 1, 0)
	if err := newDDVideoReceiver(12).receive(packet); err == nil {
		t.Fatal("accepted missing negotiated extension")
	}
}

func TestDDReceiverRejectsMarkerAndFrameBoundaryErrors(t *testing.T) {
	for _, mutate := range []func(*rtp.Packet){
		func(packet *rtp.Packet) { packet.Marker = true },
		func(packet *rtp.Packet) { packet.Timestamp++ },
		func(packet *rtp.Packet) { packet.SSRC++ },
	} {
		video := newDDVideoReceiver(13)
		if err := video.receive(ddTestPacket(t, "80fffa80003b4000", 1, 0)); err != nil {
			t.Fatal(err)
		}

		packet := ddTestPacket(t, "00fffa0000", 2, 0)
		mutate(packet)
		if err := video.receive(packet); err == nil {
			t.Fatal("accepted invalid marker or changing frame identity")
		}
	}
}

func TestDDReceiverRejectsWrongDeltaDependencies(t *testing.T) {
	video := newDDVideoReceiver(13)
	if err := video.receive(ddTestPacket(t, "c0fffa80003b4000", 1, 0)); err != nil {
		t.Fatal(err)
	}
	// A delta frame must use the required/previous-frame dependency template,
	// not the otherwise valid switch/no-dependency template zero.
	if err := video.receive(ddTestPacket(t, "c0fffb", 2, 9000)); err == nil {
		t.Fatal("accepted a delta frame with incorrect dependency semantics")
	}
}
